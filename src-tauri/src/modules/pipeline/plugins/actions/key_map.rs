use enigo::Key;

pub fn map_key(code: u32) -> Option<Key> {
    match code {
        0x08 => Some(Key::Backspace),
        0x09 => Some(Key::Tab),
        0x0D => Some(Key::Return),
        0x10 => Some(Key::Shift),
        0x11 => Some(Key::Control),
        0x12 => Some(Key::Alt),
        0x13 => Some(Key::Pause),
        0x14 => Some(Key::CapsLock),
        0x1B => Some(Key::Escape),
        0x20 => Some(Key::Space),
        0x21 => Some(Key::PageUp),
        0x22 => Some(Key::PageDown),
        0x23 => Some(Key::End),
        0x24 => Some(Key::Home),
        0x25 => Some(Key::LeftArrow),
        0x26 => Some(Key::UpArrow),
        0x27 => Some(Key::RightArrow),
        0x28 => Some(Key::DownArrow),
        0x2D => Some(Key::Insert),
        0x2E => Some(Key::Delete),
        0x5B => Some(Key::Meta),
        0x5D => Some(Key::Apps),
        0x60 => Some(Key::Numpad0),
        0x61 => Some(Key::Numpad1),
        0x62 => Some(Key::Numpad2),
        0x63 => Some(Key::Numpad3),
        0x64 => Some(Key::Numpad4),
        0x65 => Some(Key::Numpad5),
        0x66 => Some(Key::Numpad6),
        0x67 => Some(Key::Numpad7),
        0x68 => Some(Key::Numpad8),
        0x69 => Some(Key::Numpad9),
        0x70 => Some(Key::F1),
        0x71 => Some(Key::F2),
        0x72 => Some(Key::F3),
        0x73 => Some(Key::F4),
        0x74 => Some(Key::F5),
        0x75 => Some(Key::F6),
        0x76 => Some(Key::F7),
        0x77 => Some(Key::F8),
        0x78 => Some(Key::F9),
        0x79 => Some(Key::F10),
        0x7A => Some(Key::F11),
        0x7B => Some(Key::F12),
        0x90 => Some(Key::Numlock),
        0xA0 => Some(Key::LShift),
        0xA1 => Some(Key::RShift),
        0xA2 => Some(Key::LControl),
        0xA3 => Some(Key::RControl),
        0xA4 => Some(Key::LMenu),
        0xA5 => Some(Key::RMenu),
        0x30..=0x39 => Some(Key::Other(code)),
        0x41..=0x5A => Some(Key::Other(code)),
        _ => None,
    }
}
